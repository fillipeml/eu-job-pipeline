def _pick(rng: random.Random, options: list[tuple[str, float]]) -> str:
    return rng.choices([o for o, _ in options], weights=[w for _, w in options], k=1)[0]


def generate_jobs(
    count: int = 120, seed: int = 20260101, today: datetime | None = None
) -> list[Job]:
    rng = random.Random(seed)
    today = today or datetime(2026, 9, 24, tzinfo=UTC)
    jobs: list[Job] = []
    for n in range(1, count + 1):
        company, location, country = rng.choice(COMPANIES)
        role = rng.choice(ROLES)
        level = _pick(rng, SENIORITY)
        title = f"{level}{role}"
        years = {"Junior ": "0-2", "": "2-4", "Senior ": "5+", "Staff ": "8+"}[level]
        skills = rng.sample(SKILL_LINES, k=rng.randint(3, 6))
        language = _pick(rng, LANGUAGE_LINES)
        visa = _pick(rng, VISA_LINES)
        workplace = _pick(rng, WORKPLACE_LINES)
        team = rng.choice(["platform", "data", "AI", "product"])
        description = "\n\n".join(
            part
            for part in [
                f"{company} is hiring a {title} to join our {team} team in {location}.",
                "What you will work with:\n" + "\n".join(f"- {s}" for s in skills),
                f"Experience: {years} years in a similar role.",
                language,
                visa,
                workplace,
                "This posting is synthetic demo data generated by eu-job-pipeline. The company does not exist.",
            ]
            if part
        )
        source = rng.choice(SOURCES)
        jobs.append(
            Job(
                source=source,
                external_id=f"demo-{n:04d}",
                title=title,
                company=company,
                location=location,
                country=country,
                remote="remote" in workplace.lower(),
                url=f"https://example.com/jobs/{source}/demo-{n:04d}",
                description=description,
                posted_at=(today - timedelta(days=rng.randint(0, 45))).date(),
                tags=[role.split(" (")[0], level.strip() or "Mid"],
            )
        )
    return jobs


