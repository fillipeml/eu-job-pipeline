def fixture_transport(fixtures_dir: Path) -> httpx.MockTransport:
    """Serves recorded API responses so `fetch` works offline in demo mode and in tests."""

    def handler(request: httpx.Request) -> httpx.Response:
        name = _HOST_TO_FIXTURE.get(request.url.host)
        if not name:
            return httpx.Response(404, json={"error": f"no fixture for {request.url.host}"})
        path = Path(fixtures_dir) / "sources" / name
        if not path.exists():
            return httpx.Response(404, json={"error": f"missing fixture {path.name}"})
        return httpx.Response(
            200, content=path.read_bytes(), headers={"content-type": "application/json"}
        )

    return httpx.MockTransport(handler)


def write_fixture(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
